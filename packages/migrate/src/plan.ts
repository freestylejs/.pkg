import { join } from 'node:path'
import type {
    Change,
    JsoncEdit,
    MigrationPlan,
    PlanPhase,
    RepoSnapshot,
    TsupInfo,
    UnsupportedItem,
} from './types.ts'
import { hashText, pathExists, readJsonc, readText } from './utils.ts'

export type PhaseName = 'build' | 'ts7'

const VITE_PLUS_VERSION = '1.3.0'
const TYPESCRIPT_VERSION = '7.0.2'

function changeId(phase: string, path: string, description: string): string {
    return `${phase}:${path}:${description}`
}

function makeChange(change: Omit<Change, 'id'>): Change {
    return {
        id: changeId(change.phase, change.path, change.description),
        ...change,
    }
}

function packConfig(
    tsup: TsupInfo,
    root: string,
    packagePath: string,
    useTsgo: boolean
): string {
    const entry = Object.values(tsup.entry)
    const entries = entry.length > 0 ? entry : ['src/index.ts']
    const formats = tsup.format.length > 0 ? tsup.format : ['esm', 'cjs']
    const dts =
        tsup.dts === false
            ? 'false'
            : useTsgo
              ? "{ generator: 'tsgo', tsconfig: './tsconfig.build.json' }"
              : "{ tsconfig: './tsconfig.build.json' }"
    const lines = [
        '// Generated by @freestylejs/migrate. Safe to edit after migration.',
        "import { defineConfig } from 'vite-plus'",
        '',
        'export default defineConfig({',
        '    pack: {',
        `        entry: ${JSON.stringify(entries)},`,
        `        format: ${JSON.stringify(formats)},`,
        `        dts: ${dts},`,
        '        fixedExtension: false,',
        `        sourcemap: ${String(tsup.sourcemap ?? false)},`,
        `        target: ${JSON.stringify(tsup.target ?? 'esnext')},`,
        `        clean: ${String(tsup.clean ?? false)},`,
        `        outDir: ${JSON.stringify(tsup.outDir ?? 'dist')},`,
        tsup.platform
            ? `        platform: ${JSON.stringify(tsup.platform)},`
            : '',
        '    },',
        '})',
        '',
    ].filter((line) => line !== '')
    return lines.join('\n')
}

function ts7ConfigContent(): string {
    return `${JSON.stringify(
        {
            compilerOptions: {
                strict: true,
                target: 'es2021',
                module: 'esnext',
                lib: ['dom', 'dom.iterable', 'esnext'],
                esModuleInterop: true,
                moduleResolution: 'Bundler',
                noUncheckedIndexedAccess: true,
                exactOptionalPropertyTypes: true,
                forceConsistentCasingInFileNames: true,
                noEmit: true,
                skipLibCheck: true,
                noImplicitOverride: true,
                strictNullChecks: true,
                resolveJsonModule: true,
                types: ['node'],
            },
            exclude: ['node_modules', 'dist'],
        },
        null,
        4
    )}\n`
}

function normalizePaths(
    paths: Record<string, string[]>
): Record<string, string[]> {
    const out: Record<string, string[]> = {}
    for (const [key, values] of Object.entries(paths)) {
        out[key] = values.map((value) =>
            value.startsWith('.') || value.startsWith('/')
                ? value
                : `./${value}`
        )
    }
    return out
}

function sameJson(left: unknown, right: unknown): boolean {
    return JSON.stringify(left) === JSON.stringify(right)
}

function isRecord(value: unknown): value is Record<string, unknown> {
    return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function buildPhase(snapshot: RepoSnapshot): {
    phase: PlanPhase
    unsupported: UnsupportedItem[]
    manualActions: string[]
} {
    const changes: Change[] = []
    const unsupported: UnsupportedItem[] = []
    const manualActions: string[] = []

    const libraries = snapshot.packages.filter((pkg) => pkg.role === 'library')
    for (const pkg of libraries) {
        if (pkg.scripts.build?.includes('vp pack') && pkg.hasViteConfig) {
            manualActions.push(`${pkg.name}: already uses Vite+ pack`)
            continue
        }
        if (pkg.buildSystem !== 'tsup') {
            manualActions.push(
                `${pkg.name}: build system is ${pkg.buildSystem}; left untouched`
            )
            continue
        }
        if (!pkg.tsup) {
            unsupported.push({
                package: pkg.name,
                reason: 'tsup build script without a readable tsup.config.ts',
                action: 'manual configuration required',
            })
            continue
        }
        if (pkg.tsup.unsupported.length > 0) {
            unsupported.push({
                package: pkg.name,
                reason: `tsup config uses unsupported features: ${pkg.tsup.unsupported.join(', ')}`,
                action: 'manual pack config required',
            })
            continue
        }
        if (pkg.hasViteConfig) {
            manualActions.push(
                `${pkg.name}: vite.config.ts already exists; pack config not overwritten`
            )
        } else {
            const buildTsconfigPath = join(pkg.path, 'tsconfig.build.json')
            if (!pathExists(buildTsconfigPath)) {
                const entries = Object.values(pkg.tsup.entry)
                const include = entries.length > 0 ? entries : ['src/index.ts']
                changes.push(
                    makeChange({
                        phase: 'build',
                        kind: 'write-file',
                        path: buildTsconfigPath,
                        description:
                            'exclude tests from declaration generation',
                        content: `${JSON.stringify(
                            {
                                extends: './tsconfig.json',
                                include,
                                exclude: [
                                    'src/**/__tests__/**',
                                    'src/**/*.test.*',
                                    'src/**/*.spec.*',
                                ],
                            },
                            null,
                            4
                        )}\n`,
                    })
                )
            }
            changes.push(
                makeChange({
                    phase: 'build',
                    kind: 'write-file',
                    path: join(pkg.path, 'vite.config.ts'),
                    description: 'create Vite+ pack config from tsup config',
                    content: packConfig(
                        pkg.tsup,
                        snapshot.root,
                        pkg.path,
                        false
                    ),
                })
            )
        }

        changes.push(
            makeChange({
                phase: 'build',
                kind: 'edit-jsonc',
                path: join(pkg.path, 'package.json'),
                description: 'replace tsup scripts with Vite+ pack',
                edits: [
                    { path: ['scripts', 'build'], value: 'vp pack' },
                    {
                        path: ['scripts', 'build:fast'],
                        value: 'vp pack --no-dts',
                    },
                    {
                        path: ['scripts', 'dev'],
                        value: 'vp pack --watch --sourcemap',
                    },
                ],
            })
        )
    }

    const rootDev = snapshot.rootPackage.devDependencies
    if (!rootDev['vite-plus']) {
        changes.push(
            makeChange({
                phase: 'build',
                kind: 'edit-jsonc',
                path: join(snapshot.root, 'package.json'),
                description: 'add Vite+ dependency',
                edits: [
                    {
                        path: ['devDependencies', 'vite-plus'],
                        value: VITE_PLUS_VERSION,
                    },
                ],
            })
        )
    }

    if (snapshot.hasTurbo && pathExists(join(snapshot.root, 'turbo.json'))) {
        const turboPath = join(snapshot.root, 'turbo.json')
        const turbo = readJsonc<Record<string, unknown>>(turboPath)
        const tasks = isRecord(turbo.tasks) ? turbo.tasks : {}
        if (!tasks['build:fast']) {
            changes.push(
                makeChange({
                    phase: 'build',
                    kind: 'edit-jsonc',
                    path: turboPath,
                    description:
                        'add build:fast task for Vite+ package scripts',
                    edits: [
                        {
                            path: ['tasks', 'build:fast'],
                            value: {
                                cache: false,
                                persistent: false,
                                dependsOn: ['^build'],
                                outputs: ['dist/**'],
                            },
                        },
                    ],
                })
            )
        }
    }

    for (const pkg of snapshot.packages) {
        if (pkg.role === 'app') {
            manualActions.push(
                `${pkg.name}: app build preserved (${pkg.buildSystem})`
            )
        }
        if (pkg.wildcardExports) {
            manualActions.push(
                `${pkg.name}: wildcard exports ${pkg.wildcardUsed ? 'used by source; preserve' : 'not detected in source; review before removing'}`
            )
        }
        if (pkg.customScripts.length > 0) {
            manualActions.push(
                `${pkg.name}: custom scripts preserved: ${pkg.customScripts.join(', ')}`
            )
        }
        if (pkg.typescriptApiConsumers.length > 0) {
            unsupported.push({
                package: pkg.name,
                reason: `TypeScript API consumers present: ${pkg.typescriptApiConsumers.join(', ')}`,
                action: 'keep TypeScript 6 shim or migrate after TypeScript 7.1',
            })
        }
    }

    return {
        phase: { name: 'build', changes },
        unsupported,
        manualActions,
    }
}

function ts7Phase(snapshot: RepoSnapshot): {
    phase: PlanPhase
    unsupported: UnsupportedItem[]
    manualActions: string[]
} {
    const changes: Change[] = []
    const unsupported: UnsupportedItem[] = []
    const manualActions: string[] = []
    const libraries = snapshot.packages.filter((pkg) => pkg.role === 'library')

    if (pathExists(join(snapshot.root, 'tsconfig.ts7.json'))) {
        manualActions.push('tsconfig.ts7.json already exists; left unchanged')
    } else {
        changes.push(
            makeChange({
                phase: 'ts7',
                kind: 'write-file',
                path: join(snapshot.root, 'tsconfig.ts7.json'),
                description:
                    'add local TypeScript 7 base config (until @freestylejs/config@1.3.0 is published)',
                content: ts7ConfigContent(),
                overwrite: false,
            })
        )
    }

    const rootTsconfigPath = join(snapshot.root, 'tsconfig.json')
    const rootRaw = readJsonc<Record<string, unknown>>(rootTsconfigPath)
    const rootCompiler = (rootRaw.compilerOptions ?? {}) as Record<
        string,
        unknown
    >
    const rootEdits: JsoncEdit[] = []
    if (rootRaw.extends !== './tsconfig.ts7.json') {
        rootEdits.push({ path: ['extends'], value: './tsconfig.ts7.json' })
    }
    if (rootCompiler.ignoreDeprecations !== undefined) {
        rootEdits.push({
            path: ['compilerOptions', 'ignoreDeprecations'],
            value: undefined,
        })
    }
    if (
        snapshot.rootPackage.tsconfig?.paths &&
        Object.keys(snapshot.rootPackage.tsconfig.paths).length > 0
    ) {
        const normalized = normalizePaths(snapshot.rootPackage.tsconfig.paths)
        if (!sameJson(rootCompiler.paths, normalized)) {
            rootEdits.push({
                path: ['compilerOptions', 'paths'],
                value: normalized,
            })
        }
    }
    if (rootEdits.length > 0) {
        changes.push(
            makeChange({
                phase: 'ts7',
                kind: 'edit-jsonc',
                path: rootTsconfigPath,
                description:
                    'switch root tsconfig to TypeScript 7 base and drop deprecated flag',
                edits: rootEdits,
            })
        )
    }

    for (const pkg of libraries) {
        if (!pkg.tsconfig) {
            unsupported.push({
                package: pkg.name,
                reason: 'library has no tsconfig.json',
                action: 'manual tsconfig required before TypeScript 7',
            })
            continue
        }
        const packageTsconfigPath = join(pkg.path, 'tsconfig.json')
        const packageRaw =
            readJsonc<Record<string, unknown>>(packageTsconfigPath)
        const packageCompiler = (packageRaw.compilerOptions ?? {}) as Record<
            string,
            unknown
        >
        const edits: JsoncEdit[] = []
        if (packageCompiler.baseUrl !== undefined) {
            edits.push({
                path: ['compilerOptions', 'baseUrl'],
                value: undefined,
            })
        }
        if (Object.keys(pkg.tsconfig.paths).length > 0) {
            const normalized = normalizePaths(pkg.tsconfig.paths)
            if (!sameJson(packageCompiler.paths, normalized)) {
                edits.push({
                    path: ['compilerOptions', 'paths'],
                    value: normalized,
                })
            }
        }
        if (edits.length > 0) {
            changes.push(
                makeChange({
                    phase: 'ts7',
                    kind: 'edit-jsonc',
                    path: join(pkg.path, 'tsconfig.json'),
                    description:
                        'make package tsconfig TypeScript 7 compatible',
                    edits,
                })
            )
        }

        if (pkg.hasViteConfig) {
            const vitePath = join(pkg.path, 'vite.config.ts')
            const exists = pathExists(vitePath)
            const generated =
                exists &&
                readText(vitePath).includes('Generated by @freestylejs/migrate')
            if ((!exists || generated) && pkg.tsup) {
                changes.push(
                    makeChange({
                        phase: 'ts7',
                        kind: 'write-file',
                        path: vitePath,
                        description: 'use tsgo declaration generator',
                        content: packConfig(
                            pkg.tsup,
                            snapshot.root,
                            pkg.path,
                            true
                        ),
                        overwrite: true,
                    })
                )
            } else if (pkg.tsup) {
                manualActions.push(
                    `${pkg.name}: existing vite.config.ts is not generated by migrate; tsgo setting not applied`
                )
            }
        } else if (pkg.tsup) {
            changes.push(
                makeChange({
                    phase: 'ts7',
                    kind: 'write-file',
                    path: join(pkg.path, 'vite.config.ts'),
                    description:
                        'create Vite+ pack config with tsgo declaration generator',
                    content: packConfig(
                        pkg.tsup,
                        snapshot.root,
                        pkg.path,
                        true
                    ),
                    overwrite: true,
                })
            )
        }
    }

    const rootDev = snapshot.rootPackage.devDependencies
    const rootPackageEdits: JsoncEdit[] = []
    if (rootDev.typescript !== TYPESCRIPT_VERSION) {
        rootPackageEdits.push({
            path: ['devDependencies', 'typescript'],
            value: TYPESCRIPT_VERSION,
        })
    }
    if (!rootDev['@types/node']) {
        rootPackageEdits.push({
            path: ['devDependencies', '@types/node'],
            value: '24.10.0',
        })
    }
    if (rootPackageEdits.length > 0) {
        changes.push(
            makeChange({
                phase: 'ts7',
                kind: 'edit-jsonc',
                path: join(snapshot.root, 'package.json'),
                description: 'pin TypeScript 7 and node types',
                edits: rootPackageEdits,
            })
        )
    }

    for (const pkg of snapshot.packages) {
        if (pkg.role === 'app') {
            manualActions.push(
                `${pkg.name}: TypeScript version and app build preserved (${pkg.buildSystem})`
            )
        }
        if (pkg.typescriptApiConsumers.length > 0) {
            unsupported.push({
                package: pkg.name,
                reason: `TypeScript API consumers present: ${pkg.typescriptApiConsumers.join(', ')}`,
                action: 'keep TypeScript 6 shim or migrate after TypeScript 7.1',
            })
        }
    }

    return {
        phase: { name: 'ts7', changes },
        unsupported,
        manualActions,
    }
}

export function createPlan(
    snapshot: RepoSnapshot,
    requestedPhases: PhaseName[]
): MigrationPlan {
    const phaseBuilders: Record<
        PhaseName,
        (repo: RepoSnapshot) => ReturnType<typeof buildPhase>
    > = {
        build: buildPhase,
        ts7: ts7Phase,
    }
    const phases: PlanPhase[] = []
    const unsupported: UnsupportedItem[] = []
    const manualActions: string[] = []
    for (const phase of requestedPhases) {
        const result = phaseBuilders[phase](snapshot)
        phases.push(result.phase)
        unsupported.push(...result.unsupported)
        manualActions.push(...result.manualActions)
    }

    const planBase = {
        schemaVersion: 1 as const,
        repo: snapshot.root,
        repoName: snapshot.rootPackage.name,
        generatedAt: new Date().toISOString(),
        branch: snapshot.gitBranch ?? 'unknown',
        head: snapshot.gitHead ?? 'unknown',
        phases,
        unsupported,
        manualActions,
    }
    const planHash = hashText(
        JSON.stringify({
            repo: planBase.repoName,
            branch: planBase.branch,
            head: planBase.head,
            phases,
            unsupported,
        })
    )
    return { ...planBase, planHash }
}
